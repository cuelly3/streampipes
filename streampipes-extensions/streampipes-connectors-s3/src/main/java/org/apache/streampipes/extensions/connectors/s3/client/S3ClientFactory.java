package org.apache.streampipes.extensions.connectors.s3.client;

import software.amazon.awssdk.auth.credentials.AwsBasicCredentials;
import software.amazon.awssdk.auth.credentials.StaticCredentialsProvider;
import software.amazon.awssdk.core.checksums.RequestChecksumCalculation;
import software.amazon.awssdk.core.checksums.ResponseChecksumValidation;
import software.amazon.awssdk.regions.Region;
import software.amazon.awssdk.services.s3.S3Client;

import java.net.URI;


public final class S3ClientFactory {

  private S3ClientFactory() {
  }

  public static S3Client create(S3ConnectionSettings settings) {
    return S3Client.builder()
        .endpointOverride(URI.create(settings.endpointUrl()))
        .region(Region.of(settings.region()))
        .forcePathStyle(true)
        .requestChecksumCalculation(RequestChecksumCalculation.WHEN_REQUIRED)
        .responseChecksumValidation(ResponseChecksumValidation.WHEN_REQUIRED)
        .credentialsProvider(StaticCredentialsProvider.create(
            AwsBasicCredentials.create(settings.accessKey(), settings.secretKey())))
        .build();
  }
}
